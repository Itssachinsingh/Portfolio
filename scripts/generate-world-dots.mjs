// Rasterises the country outlines in data/globe.json into the dot grid behind the scroll story's map.
// Run with: node scripts/generate-world-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";

const STEP = 2;
const LAT_TOP = 78;
const LAT_BOTTOM = -58;

const { features } = JSON.parse(
  readFileSync(new URL("../data/globe.json", import.meta.url), "utf8")
);

const polygons = features.flatMap(({ geometry }) =>
  geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates
);

// even-odd ray casting; holes are just further rings that flip the result back
const inRing = (x, y, ring) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
};

const isLand = (lon, lat) =>
  polygons.some((rings) =>
    rings.reduce((inside, ring) => (inRing(lon, lat, ring) ? !inside : inside), false)
  );

const rows = [];
for (let lat = LAT_TOP; lat >= LAT_BOTTOM; lat -= STEP) {
  let row = "";
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) {
    row += isLand(lon, lat) ? "1" : "0";
  }
  rows.push(row);
}

const out = `// Generated by scripts/generate-world-dots.mjs from data/globe.json. Do not edit by hand.
export const WORLD_DOTS = {
  step: ${STEP},
  latTop: ${LAT_TOP},
  latBottom: ${LAT_BOTTOM},
  rows: [
${rows.map((row) => `    "${row}",`).join("\n")}
  ],
};
`;

writeFileSync(new URL("../data/worldDots.ts", import.meta.url), out);
console.log(`wrote ${rows.length} rows x ${rows[0].length} cols`);
